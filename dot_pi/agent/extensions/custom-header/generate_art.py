#!/usr/bin/env python3
"""Turn a photo into art.ts for the custom-header extension, using ascii_magic.

Usage:
    pip install ascii_magic
    python3 generate_art.py PHOTO [--columns 56] [--crop LEFT,TOP,RIGHT,BOTTOM]

Writes art.ts next to this script; run /reload in pi to see it.
Each cell gets ascii_magic's density character and the pixel's true colour.
"""

import argparse
import json
from pathlib import Path

from ascii_magic import AsciiArt
from PIL import Image


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("photo", type=Path)
    parser.add_argument("--columns", type=int, default=56)
    parser.add_argument("--crop", help="LEFT,TOP,RIGHT,BOTTOM in pixels")
    args = parser.parse_args()

    img = Image.open(args.photo).convert("RGB")
    if args.crop:
        img = img.crop(tuple(int(v) for v in args.crop.split(",")))

    cells = AsciiArt.from_pillow_image(img).to_character_list(
        columns=args.columns, width_ratio=2.0, full_color=True
    )

    lines = []
    for row in cells:
        out, last = "", None
        for cell in row:
            color = cell["full-hex-color"].lstrip("#")
            if color != last:
                r, g, b = (int(color[i : i + 2], 16) for i in (0, 2, 4))
                out += f"\x1b[38;2;{r};{g};{b}m"
                last = color
            out += cell["character"]
        lines.append(out + "\x1b[39m")

    target = Path(__file__).with_name("art.ts")
    body = ",\n".join(f"\t{json.dumps(line)}" for line in lines)
    target.write_text(
        "// Generated by generate_art.py from a photo with ascii_magic. Do not edit by hand.\n"
        f"export const ART_WIDTH = {args.columns};\n"
        f"export const ART: string[] = [\n{body},\n];\n"
    )
    print(f"wrote {target} ({args.columns}x{len(lines)})")


if __name__ == "__main__":
    main()
